#!/bin/bash

#устанавливаем путь, куда будем отправлять бэкапы - директория уже должна быть создана на сервере!
BACKUP_DIR="/home/backupuser/wiki_content"
#устанавливаем путь к тому, что будем бэкапить - в данном случае папку со всеми файлами mediawiki
TARGET_DIR="/var/www/"
#директория, которую буждем копировать
WIKI_DIR="mediawiki-1.42.1"
#ip-адрес сервера для хранения бэкапов
IP="192.168.0.100"
#имя пользователь для отправки бэкапов
NAME="backupuser"

#функция генерации имени архива бэкапа
make_name(){
archive_name="backup_media_wiki_$(date +%Y-%m-%d_%H-%M).tar.gz"
}

#НАЧАЛО РАБОТЫ КОДА

#проверяем доступность сервера хранения бэкапов
if /bin/ping -c4 "$IP" &> /dev/null
then

    make_name
    #архивируем директорию и сохраняем ее в /tmp
    tar -czpf /tmp/"$archive_name" -C "$TARGET_DIR" "$WIKI_DIR"

    # Проверяем, что архив создался (на случай нехватки места)
    if [ $? -ne 0 ]; then
        echo "Ошибка создания архива!"
        exit 1
    fi

    #отправялем по scp файл архива. Для этого устанавливаем соединение под специально созданным для этого пользователем 
    #пользователь должен существовать на сервере хранения бэкапов!
    echo "Подготовка к отправке бэкапа"
    scp -i /var/lib/backup_wiki/.ssh/id_ed25519 -o StrictHostKeyChecking=accept-new /tmp/"$archive_name" "$NAME@$IP:$BACKUP_DIR"

    #проверяем код выполнения scp и успешность отправки файла
    if [ $? -eq 0 ]; then
        echo "Копирование успешно."
        rm -f /tmp/"$archive_name"
        exit 0
    else
        echo "Ошибка при отправке архива на сервер!"
        # Локальный архив не удаляем, чтобы его можно было проверить/отправить вручную
        exit 10
    fi

#если сервер недоступен, то завершаем скрипт
else

    echo "Сервер для резервного копирования недоступен!"

    exit 1

fi
